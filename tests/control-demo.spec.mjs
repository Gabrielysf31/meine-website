import { test, expect } from '@playwright/test';

for (const [device, width] of [['Desktop', 1440], ['Mobil', 375]]) {
  test(`Taster und App bedienen denselben Raum auf ${device}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 });
    await page.goto('/smart-home/');
    const demo = page.locator('[data-control-demo]');
    const requests = [];
    page.on('request', request => { if (['fetch', 'xhr', 'websocket'].includes(request.resourceType())) requests.push(request.url()); });
    await demo.getByRole('button', { name: 'Licht ausschalten, zum Dunklerdimmen halten', exact: true }).click();
    await expect(demo.locator('[data-control-light]')).toHaveText('Aus');
    await expect(demo.locator('[data-control-room]')).toHaveAccessibleName(/ausgeschaltet/);
    await demo.getByRole('button', { name: '+ Heller', exact: true }).click();
    await expect(demo.locator('[data-control-light]')).toHaveText('10 %');
    const on = demo.getByRole('button', { name: 'Licht einschalten, zum Hellerdimmen halten', exact: true });
    await on.scrollIntoViewIfNeeded();
    await on.hover();
    await page.mouse.down();
    await expect.poll(() => demo.locator('[data-control-light]').textContent()).not.toBe('10 %');
    await page.mouse.up();
    const heldLevel = await demo.locator('[data-control-light]').textContent();
    await page.waitForTimeout(400);
    await expect(demo.locator('[data-control-light]')).toHaveText(heldLevel);
    await demo.getByRole('button', { name: 'Jalousie am Taster schließen', exact: true }).click();
    await expect(demo.locator('[data-control-blinds]')).toHaveText('Geschlossen');
    await expect(page.locator('#shade-wohnen')).toHaveAttribute('data-position', 'open');
    await demo.getByRole('tab', { name: 'App', exact: true }).click();
    await expect(demo.locator('#control-brightness')).toHaveValue(heldLevel.replace(' %', ''));
    await demo.getByRole('slider').fill('35');
    await expect(demo.locator('[data-control-light]')).toHaveText('35 %');
    await demo.getByRole('slider').focus();
    await page.keyboard.press('ArrowRight');
    await expect(demo.locator('[data-control-light]')).toHaveText('40 %');
    await demo.getByRole('button', { name: 'Öffnen', exact: true }).click();
    await expect(demo.locator('[data-control-blinds]')).toHaveText('Offen');
    if (device === 'Mobil') await expect(demo.locator('[data-control-room]')).toBeInViewport();
    await demo.getByRole('tab', { name: 'App', exact: true }).focus();
    await page.keyboard.press('ArrowLeft');
    await expect(demo.getByRole('tab', { name: 'Taster', exact: true })).toHaveAttribute('aria-selected', 'true');
    await expect(demo.locator('[data-control-light]')).toHaveText('40 %');
    const off = demo.getByRole('button', { name: 'Licht ausschalten, zum Dunklerdimmen halten', exact: true });
    await off.scrollIntoViewIfNeeded();
    await off.hover();
    await page.mouse.down();
    await page.waitForTimeout(520);
    await page.mouse.up();
    const dimmed = await demo.locator('[data-control-light]').textContent();
    expect(dimmed).not.toBe('Aus');
    expect(parseInt(dimmed)).toBeLessThan(40);
    await demo.getByRole('button', { name: 'Demo zurücksetzen', exact: true }).click();
    await expect(demo.locator('[data-control-light]')).toHaveText('65 %');
    expect(requests).toEqual([]);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  });
}

test('Automatik führt veränderbare Zeiten geordnet aus und lässt sich übersteuern', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/smart-home/');
  const demo = page.locator('[data-control-demo]');
  await demo.getByRole('tab', { name: 'Automatik', exact: true }).click();
  await demo.getByRole('button', { name: 'Simulation starten', exact: true }).click();
  await expect(demo.locator('[data-control-clock]')).toHaveText('07:59');
  await expect(demo.locator('[data-control-light]')).toHaveText('Aus');
  await expect(demo.locator('[data-control-events]')).toContainText('08:00 · Licht automatisch ausgeschaltet.');
  await expect(demo.locator('[data-control-blinds]')).toHaveText('Geschlossen');
  await expect(demo.locator('[data-control-clock]')).toHaveText('10:00');
  await expect(demo.getByRole('button', { name: 'Simulation starten', exact: true })).toBeEnabled();
  await demo.getByLabel('Licht ausschalten', { exact: true }).fill('18:30');
  await demo.getByLabel('Jalousie schließen', { exact: true }).fill('17:15');
  await demo.getByRole('button', { name: 'Simulation starten', exact: true }).click();
  await expect(demo.locator('[data-control-events] li').first()).toHaveText('17:15 · Jalousie automatisch geschlossen.');
  await expect(demo.locator('[data-control-light]')).toHaveText('65 %');
  await expect(demo.locator('[data-control-events] li')).toHaveCount(2);
  await demo.getByRole('button', { name: 'Simulation starten', exact: true }).click();
  await demo.getByRole('tab', { name: 'Taster', exact: true }).click();
  await expect(demo.locator('[data-control-status]')).toContainText('gestoppt');
  await demo.getByRole('button', { name: 'Jalousie am Taster schließen', exact: true }).click();
  await page.waitForTimeout(1500);
  await expect(demo.locator('[data-control-light]')).toHaveText('65 %');
  await expect(demo.locator('[data-control-events] li')).toHaveCount(0);
  await expect(demo.locator('.control-room-blinds')).toHaveCSS('transition-duration', '0s');
  await demo.getByRole('tab', { name: 'Automatik', exact: true }).click();
  await demo.getByLabel('Licht ausschalten', { exact: true }).fill('12:00');
  await demo.getByLabel('Jalousie schließen', { exact: true }).fill('12:00');
  await demo.getByRole('button', { name: 'Simulation starten', exact: true }).click();
  await expect(demo.locator('[data-control-events] li')).toHaveCount(2);
  await expect(demo.locator('[data-control-light]')).toHaveText('Aus');
  await expect(demo.locator('[data-control-blinds]')).toHaveText('Geschlossen');
  await page.reload();
  await expect(demo.locator('[data-control-light]')).toHaveText('65 %');
  await expect(demo.getByRole('tab', { name: 'Taster', exact: true })).toHaveAttribute('aria-selected', 'true');
});

test('Ohne JavaScript bleibt die Bedienungsdemo als erklärte Illustration sichtbar', async ({ browser }) => {
  const context = await browser.newContext({ javaScriptEnabled: false });
  const page = await context.newPage();
  await page.goto('/smart-home/');
  const demo = page.locator('[data-control-demo]');
  await expect(demo.locator('[data-control-room]')).toHaveAccessibleName(/65 Prozent, Jalousie offen/);
  await expect(demo.locator('.control-interactive')).toBeHidden();
  await expect(demo.getByText('Zum Ausprobieren der drei Bedienungsarten benötigst du JavaScript.', { exact: false })).toBeVisible();
  await context.close();
});
